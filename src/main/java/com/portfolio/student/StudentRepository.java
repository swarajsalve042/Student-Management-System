package com.portfolio.student;

import java.sql.*;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;
import java.util.regex.Pattern;

public class StudentRepository {
    private static final Pattern EMAIL_PATTERN =
            Pattern.compile("^[A-Za-z0-9.!#$%&'*+/=?^_`{|}~-]+@[A-Za-z0-9-]+(?:\\.[A-Za-z0-9-]+)+$");

    private final String jdbcUrl;

    public StudentRepository(String jdbcUrl) {
        if (jdbcUrl == null || !jdbcUrl.startsWith("jdbc:")) {
            throw new IllegalArgumentException("A valid JDBC URL is required");
        }
        this.jdbcUrl = jdbcUrl;
    }

    private Connection connect() throws SQLException {
        return DriverManager.getConnection(jdbcUrl);
    }

    public void initialize() throws SQLException {
        try (Connection connection = connect(); Statement statement = connection.createStatement()) {
            statement.execute("CREATE TABLE IF NOT EXISTS students ("
                    + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + "name VARCHAR(120) NOT NULL,"
                    + "email VARCHAR(160) NOT NULL UNIQUE,"
                    + "course VARCHAR(120) NOT NULL)");
        }
    }

    public long add(String name, String email, String course) throws SQLException {
        validate(name, email, course);
        String sql = "INSERT INTO students(name,email,course) VALUES(?,?,?)";
        try (Connection connection = connect();
             PreparedStatement statement = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            bindStudent(statement, name, email, course);
            statement.executeUpdate();
            try (ResultSet keys = statement.getGeneratedKeys()) {
                if (!keys.next()) {
                    throw new SQLException("Database did not return a generated student ID");
                }
                return keys.getLong(1);
            }
        }
    }

    public List<String> findAll() throws SQLException {
        List<String> rows = new ArrayList<>();
        String sql = "SELECT id,name,email,course FROM students ORDER BY id";
        try (Connection connection = connect();
             Statement statement = connection.createStatement();
             ResultSet result = statement.executeQuery(sql)) {
            while (result.next()) {
                rows.add(result.getLong("id") + "|" + result.getString("name") + "|"
                        + result.getString("email") + "|" + result.getString("course"));
            }
        }
        return rows;
    }

    public Optional<String> findById(long id) throws SQLException {
        if (id <= 0) {
            throw new IllegalArgumentException("Student ID must be positive");
        }
        String sql = "SELECT id,name,email,course FROM students WHERE id=?";
        try (Connection connection = connect();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setLong(1, id);
            try (ResultSet result = statement.executeQuery()) {
                if (!result.next()) {
                    return Optional.empty();
                }
                return Optional.of(result.getLong("id") + "|" + result.getString("name") + "|"
                        + result.getString("email") + "|" + result.getString("course"));
            }
        }
    }

    public boolean update(long id, String name, String email, String course) throws SQLException {
        if (id <= 0) {
            throw new IllegalArgumentException("Student ID must be positive");
        }
        validate(name, email, course);
        String sql = "UPDATE students SET name=?, email=?, course=? WHERE id=?";
        try (Connection connection = connect();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            bindStudent(statement, name, email, course);
            statement.setLong(4, id);
            return statement.executeUpdate() == 1;
        }
    }

    public boolean delete(long id) throws SQLException {
        if (id <= 0) {
            throw new IllegalArgumentException("Student ID must be positive");
        }
        try (Connection connection = connect();
             PreparedStatement statement = connection.prepareStatement("DELETE FROM students WHERE id=?")) {
            statement.setLong(1, id);
            return statement.executeUpdate() == 1;
        }
    }

    private void bindStudent(PreparedStatement statement, String name, String email, String course)
            throws SQLException {
        statement.setString(1, name.trim());
        statement.setString(2, email.trim().toLowerCase());
        statement.setString(3, course.trim());
    }

    private void validate(String name, String email, String course) {
        if (name == null || name.isBlank() || name.trim().length() > 120
                || email == null || email.isBlank() || email.trim().length() > 160
                || !EMAIL_PATTERN.matcher(email.trim()).matches()
                || course == null || course.isBlank() || course.trim().length() > 120) {
            throw new IllegalArgumentException(
                    "Name and course (1-120 characters) and a valid email (max 160 characters) are required");
        }
    }
}
